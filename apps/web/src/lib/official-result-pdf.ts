import { createResultQrMatrix } from './result-qr';
import type { OfficialResult } from './result-publication';

const PAGE_WIDTH = 595;
const PAGE_HEIGHT = 842;
const MARGIN = 42;
const COURSE_ROWS_PER_PAGE = 9;

export function buildOfficialResultPdf(result: OfficialResult) {
  if (result.publication.integrity !== 'VERIFIED' || !result.publication.verificationUrl) {
    throw new Error('Only integrity-verified published results can be exported as an official PDF.');
  }

  const chunks = chunk(result.courses, COURSE_ROWS_PER_PAGE);
  const pages = chunks.map((courses, index) => renderPage(result, courses, index, chunks.length));
  return assemblePdf(pages, {
    title: `${result.institution.name} - Official Result - ${result.student.rollNumber}`,
    author: result.institution.name,
    subject: result.examination.name,
  });
}

function renderPage(result: OfficialResult, courses: OfficialResult['courses'], pageIndex: number, pageCount: number) {
  const commands: string[] = [];
  const isLastPage = pageIndex === pageCount - 1;

  // Page border and institutional masthead.
  stroke(commands, 0.16, 0.24, 0.38);
  lineWidth(commands, 1.2);
  rect(commands, 28, 28, PAGE_WIDTH - 56, PAGE_HEIGHT - 56, false, true);
  fill(commands, 0.06, 0.12, 0.23);
  rect(commands, 29, PAGE_HEIGHT - 126, PAGE_WIDTH - 58, 97, true, false);

  text(commands, MARGIN, PAGE_HEIGHT - 61, 17, result.institution.name.toUpperCase(), true, [1, 1, 1]);
  text(commands, MARGIN, PAGE_HEIGHT - 82, 8.7, 'OFFICE OF THE CONTROLLER OF EXAMINATIONS', true, [0.76, 0.84, 0.94]);
  text(commands, MARGIN, PAGE_HEIGHT - 102, 12, 'OFFICIAL STATEMENT OF MARKS AND GRADE CARD', true, [1, 1, 1]);

  text(commands, PAGE_WIDTH - MARGIN, PAGE_HEIGHT - 60, 8, `PAGE ${pageIndex + 1} OF ${pageCount}`, true, [0.76, 0.84, 0.94], 'right');
  text(commands, PAGE_WIDTH - MARGIN, PAGE_HEIGHT - 80, 8, 'AUTHORIZED & PUBLISHED', true, [0.55, 0.93, 0.69], 'right');
  text(commands, PAGE_WIDTH - MARGIN, PAGE_HEIGHT - 99, 7.3, result.publication.documentNumber, false, [0.82, 0.88, 0.95], 'right');

  // Student and examination identity.
  let y = PAGE_HEIGHT - 151;
  sectionLabel(commands, MARGIN, y, 'STUDENT ACADEMIC RECORD');
  y -= 18;
  infoRow(commands, y, [
    ['Student Name', result.student.name, 185],
    ['Roll / Registration No.', result.student.rollNumber, 145],
    ['Programme', `${result.student.programme} (${result.student.programmeCode})`, 181],
  ]);
  y -= 42;
  infoRow(commands, y, [
    ['Department', result.student.department, 185],
    ['Batch / Section', `${result.student.batch}${result.student.section ? ` / ${result.student.section}` : ''}`, 145],
    ['Academic Session', result.examination.academicYear, 181],
  ]);
  y -= 42;
  infoRow(commands, y, [
    ['Examination', result.examination.name, 260],
    ['Term / Semester', `${result.examination.term} (Semester ${result.examination.termNumber})`, 120],
    ['Result Status', result.academicIndex.resultStatus, 131],
  ]);
  y -= 45;

  sectionLabel(commands, MARGIN, y, pageIndex === 0 ? 'COURSE-WISE PERFORMANCE' : 'COURSE-WISE PERFORMANCE - CONTINUED');
  y -= 19;
  y = drawCourseTable(commands, y, courses);

  if (isLastPage) {
    y -= 16;
    drawAcademicSummary(commands, result, y);
    drawAuthorization(commands, result, 152);
    drawVerification(commands, result, 60);
  } else {
    text(commands, MARGIN, 56, 7.5, 'Course table continues on the next page. This page forms part of the same digitally verifiable result document.', false, [0.34, 0.4, 0.49]);
  }

  text(commands, PAGE_WIDTH / 2, 39, 6.8, 'Generated by CampusOS from the institution-authorised academic record. Verify before relying on a printed or copied version.', false, [0.42, 0.47, 0.55], 'center');
  return commands.join('\n');
}

function drawCourseTable(commands: string[], startY: number, courses: OfficialResult['courses']) {
  const columns = [
    { label: 'CODE', width: 52 },
    { label: 'COURSE TITLE', width: 166 },
    { label: 'CR', width: 33 },
    { label: 'MARKS', width: 54 },
    { label: 'MAX', width: 42 },
    { label: 'GRADE', width: 46 },
    { label: 'GP', width: 36 },
    { label: 'STATUS', width: 54 },
  ];
  const tableWidth = columns.reduce((sum, column) => sum + column.width, 0);
  const x = MARGIN;
  let y = startY;

  fill(commands, 0.92, 0.95, 0.98);
  rect(commands, x, y - 22, tableWidth, 22, true, false);
  stroke(commands, 0.75, 0.8, 0.86);
  lineWidth(commands, 0.55);
  rect(commands, x, y - 22, tableWidth, 22, false, true);

  let cursor = x;
  for (const column of columns) {
    text(commands, cursor + 4, y - 14, 6.7, column.label, true, [0.18, 0.26, 0.38]);
    cursor += column.width;
    line(commands, cursor, y, cursor, y - 22);
  }
  y -= 22;

  for (const course of courses) {
    const rowHeight = 31;
    stroke(commands, 0.82, 0.85, 0.89);
    rect(commands, x, y - rowHeight, tableWidth, rowHeight, false, true);
    cursor = x;
    const values = [
      course.code,
      course.title,
      String(course.credits),
      formatNumber(course.marksObtained),
      course.maxMarks === null ? '-' : formatNumber(course.maxMarks),
      course.grade,
      formatNumber(course.gradePoints),
      course.isPass ? 'PASS' : 'NOT PASS',
    ];
    for (let index = 0; index < columns.length; index += 1) {
      const column = columns[index];
      const value = values[index];
      if (index === 1) {
        const lines = wrapText(value, 34);
        text(commands, cursor + 4, y - 11, 7.2, lines[0] ?? '', false, [0.12, 0.16, 0.23]);
        if (lines[1]) text(commands, cursor + 4, y - 21, 6.5, lines[1], false, [0.34, 0.4, 0.49]);
      } else {
        text(commands, cursor + 4, y - 18, index === 0 ? 7.3 : 7, value, index === 0 || index === 5 || index === 7, index === 7 && course.isPass ? [0.08, 0.45, 0.26] : [0.12, 0.16, 0.23]);
      }
      cursor += column.width;
      line(commands, cursor, y, cursor, y - rowHeight);
    }
    y -= rowHeight;
  }
  return y;
}

function drawAcademicSummary(commands: string[], result: OfficialResult, startY: number) {
  sectionLabel(commands, MARGIN, startY, 'CUMULATIVE ACADEMIC INDEX');
  const y = startY - 48;
  const cards = [
    ['Semester SGPA', result.academicIndex.sgpa.toFixed(2)],
    ['Cumulative CGPA', result.academicIndex.cgpa.toFixed(2)],
    ['Credits Earned', `${result.academicIndex.earnedCredits} / ${result.academicIndex.totalCredits}`],
    ['Aggregate', result.academicIndex.percentage === null ? 'N/A' : `${result.academicIndex.percentage.toFixed(2)}%`],
  ];
  const gap = 8;
  const width = (PAGE_WIDTH - MARGIN * 2 - gap * 3) / 4;
  cards.forEach(([label, value], index) => {
    const x = MARGIN + index * (width + gap);
    fill(commands, 0.965, 0.975, 0.99);
    rect(commands, x, y, width, 39, true, false);
    stroke(commands, 0.82, 0.86, 0.91);
    rect(commands, x, y, width, 39, false, true);
    text(commands, x + 7, y + 25, 6.3, label.toUpperCase(), true, [0.4, 0.46, 0.55]);
    text(commands, x + 7, y + 8, 12, value, true, [0.06, 0.2, 0.4]);
  });
}

function drawAuthorization(commands: string[], result: OfficialResult, y: number) {
  sectionLabel(commands, MARGIN, y + 47, 'ACADEMIC AUTHORIZATION TRAIL');
  const faculty = result.approvals.filter((approval) => approval.stage === 'FACULTY');
  const hod = result.approvals.filter((approval) => approval.stage === 'HOD');
  const dean = result.approvals.find((approval) => approval.stage === 'DEAN');

  const entries = [
    ['Course Faculty', `${faculty.filter((item) => item.approved).length}/${faculty.length} course certification(s) completed`],
    ['Head(s) of Department', `${hod.filter((item) => item.approved).length}/${hod.length} department approval(s) completed`],
    ['Academic Dean', dean?.approved ? `${dean.approverName ?? 'Dean'} - approved ${formatPdfDate(dean.approvedAt)}` : 'Pending'],
    ['Published By', `${result.publication.publisherName ?? 'Authorised examination office'} (${humanRole(result.publication.publisherRole)}) - ${formatPdfDate(result.publication.publishedAt)}`],
  ];

  const width = (PAGE_WIDTH - MARGIN * 2 - 8) / 2;
  entries.forEach(([label, value], index) => {
    const col = index % 2;
    const row = Math.floor(index / 2);
    const x = MARGIN + col * (width + 8);
    const boxY = y - row * 32;
    stroke(commands, 0.82, 0.86, 0.91);
    rect(commands, x, boxY, width, 26, false, true);
    text(commands, x + 6, boxY + 16, 6.1, label.toUpperCase(), true, [0.42, 0.47, 0.55]);
    text(commands, x + 6, boxY + 6, 6.4, fitText(value, 54), false, [0.15, 0.2, 0.28]);
  });
}

function drawVerification(commands: string[], result: OfficialResult, y: number) {
  const url = result.publication.verificationUrl!;
  const matrix = createResultQrMatrix(url);
  const boxHeight = 76;
  fill(commands, 0.97, 0.98, 0.99);
  rect(commands, MARGIN, y, PAGE_WIDTH - MARGIN * 2, boxHeight, true, false);
  stroke(commands, 0.78, 0.83, 0.89);
  rect(commands, MARGIN, y, PAGE_WIDTH - MARGIN * 2, boxHeight, false, true);

  const qrSize = 62;
  const qrX = MARGIN + 7;
  const qrY = y + 7;
  if (matrix) {
    const quiet = 4;
    const module = qrSize / (matrix.length + quiet * 2);
    fill(commands, 1, 1, 1);
    rect(commands, qrX, qrY, qrSize, qrSize, true, false);
    fill(commands, 0.05, 0.07, 0.1);
    for (let row = 0; row < matrix.length; row += 1) {
      for (let column = 0; column < matrix.length; column += 1) {
        if (!matrix[row][column]) continue;
        rect(commands, qrX + (column + quiet) * module, qrY + qrSize - (row + quiet + 1) * module, module + 0.03, module + 0.03, true, false);
      }
    }
  }

  const textX = matrix ? qrX + qrSize + 12 : MARGIN + 10;
  text(commands, textX, y + 56, 7.2, 'ONLINE RESULT VERIFICATION', true, [0.06, 0.2, 0.4]);
  text(commands, textX, y + 42, 6.4, 'Scan the QR code or open the verification address to validate this exact published academic snapshot.', false, [0.32, 0.38, 0.47]);
  text(commands, textX, y + 29, 6.2, fitText(url, 78), false, [0.12, 0.25, 0.46]);
  text(commands, textX, y + 15, 6.1, `Document No.: ${result.publication.documentNumber}`, true, [0.2, 0.27, 0.36]);
}

function sectionLabel(commands: string[], x: number, y: number, label: string) {
  fill(commands, 0.1, 0.31, 0.59);
  rect(commands, x, y - 3, 3, 12, true, false);
  text(commands, x + 9, y, 7.1, label, true, [0.18, 0.26, 0.38]);
}

function infoRow(commands: string[], y: number, fields: Array<[string, string, number]>) {
  let x = MARGIN;
  for (const [label, value, width] of fields) {
    fill(commands, 0.97, 0.98, 0.99);
    rect(commands, x, y - 10, width - 7, 35, true, false);
    stroke(commands, 0.84, 0.87, 0.91);
    rect(commands, x, y - 10, width - 7, 35, false, true);
    text(commands, x + 6, y + 13, 5.9, label.toUpperCase(), true, [0.43, 0.48, 0.56]);
    text(commands, x + 6, y - 1, 7.4, fitText(value, Math.max(18, Math.floor(width / 5.2))), true, [0.13, 0.18, 0.26]);
    x += width;
  }
}

function assemblePdf(pages: string[], metadata: { title: string; author: string; subject: string }) {
  const objects = new Map<number, string>();
  objects.set(1, '<< /Type /Catalog /Pages 2 0 R >>');
  objects.set(3, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');
  objects.set(4, '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>');

  const pageObjectNumbers: number[] = [];
  pages.forEach((content, index) => {
    const pageObject = 5 + index * 2;
    const contentObject = pageObject + 1;
    pageObjectNumbers.push(pageObject);
    objects.set(pageObject, `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_WIDTH} ${PAGE_HEIGHT}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentObject} 0 R >>`);
    objects.set(contentObject, `<< /Length ${asciiByteLength(content)} >>\nstream\n${content}\nendstream`);
  });
  objects.set(2, `<< /Type /Pages /Kids [${pageObjectNumbers.map((number) => `${number} 0 R`).join(' ')}] /Count ${pageObjectNumbers.length} >>`);

  const infoObject = 5 + pages.length * 2;
  objects.set(infoObject, `<< /Title (${pdfEscape(metadata.title)}) /Author (${pdfEscape(metadata.author)}) /Subject (${pdfEscape(metadata.subject)}) /Creator (CampusOS Official Results) /Producer (CampusOS PDF Engine) >>`);

  const maxObject = infoObject;
  let pdf = '%PDF-1.4\n%CampusOS\n';
  const offsets = new Array<number>(maxObject + 1).fill(0);
  for (let objectNumber = 1; objectNumber <= maxObject; objectNumber += 1) {
    offsets[objectNumber] = asciiByteLength(pdf);
    pdf += `${objectNumber} 0 obj\n${objects.get(objectNumber) ?? '<<>>'}\nendobj\n`;
  }

  const xrefOffset = asciiByteLength(pdf);
  pdf += `xref\n0 ${maxObject + 1}\n`;
  pdf += '0000000000 65535 f \n';
  for (let objectNumber = 1; objectNumber <= maxObject; objectNumber += 1) {
    pdf += `${String(offsets[objectNumber]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${maxObject + 1} /Root 1 0 R /Info ${infoObject} 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;
  return new TextEncoder().encode(pdf);
}

function text(
  commands: string[],
  x: number,
  y: number,
  size: number,
  value: string,
  bold = false,
  color: [number, number, number] = [0.1, 0.13, 0.18],
  align: 'left' | 'center' | 'right' = 'left',
) {
  const safe = printable(value);
  const estimatedWidth = safe.length * size * (bold ? 0.56 : 0.5);
  const adjustedX = align === 'center' ? x - estimatedWidth / 2 : align === 'right' ? x - estimatedWidth : x;
  commands.push(`${color.join(' ')} rg`);
  commands.push(`BT /${bold ? 'F2' : 'F1'} ${size.toFixed(2)} Tf ${adjustedX.toFixed(2)} ${y.toFixed(2)} Td (${pdfEscape(safe)}) Tj ET`);
}

function fill(commands: string[], r: number, g: number, b: number) {
  commands.push(`${r} ${g} ${b} rg`);
}

function stroke(commands: string[], r: number, g: number, b: number) {
  commands.push(`${r} ${g} ${b} RG`);
}

function lineWidth(commands: string[], width: number) {
  commands.push(`${width} w`);
}

function rect(commands: string[], x: number, y: number, width: number, height: number, doFill: boolean, doStroke: boolean) {
  const operator = doFill && doStroke ? 'B' : doFill ? 'f' : 'S';
  commands.push(`${x.toFixed(2)} ${y.toFixed(2)} ${width.toFixed(2)} ${height.toFixed(2)} re ${operator}`);
}

function line(commands: string[], x1: number, y1: number, x2: number, y2: number) {
  commands.push(`${x1.toFixed(2)} ${y1.toFixed(2)} m ${x2.toFixed(2)} ${y2.toFixed(2)} l S`);
}

function pdfEscape(value: string) {
  return printable(value).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function printable(value: string) {
  return value.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/[^\x20-\x7E]/g, '?');
}

function asciiByteLength(value: string) {
  return new TextEncoder().encode(value).byteLength;
}

function wrapText(value: string, width: number) {
  const words = printable(value).split(/\s+/);
  const lines: string[] = [];
  let current = '';
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word;
    if (candidate.length <= width) current = candidate;
    else {
      if (current) lines.push(current);
      current = word;
    }
  }
  if (current) lines.push(current);
  return lines.slice(0, 2);
}

function fitText(value: string, width: number) {
  const safe = printable(value);
  return safe.length <= width ? safe : `${safe.slice(0, Math.max(1, width - 3))}...`;
}

function formatNumber(value: number) {
  return Number.isInteger(value) ? String(value) : value.toFixed(2).replace(/0+$/, '').replace(/\.$/, '');
}

function formatPdfDate(value: string | null) {
  if (!value) return 'date unavailable';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return 'date unavailable';
  return date.toISOString().replace('T', ' ').slice(0, 16) + ' UTC';
}

function humanRole(value: string | null) {
  if (!value) return 'Authorised Office';
  return value.toLowerCase().replace(/_/g, ' ').replace(/\b\w/g, (character) => character.toUpperCase());
}

function chunk<T>(items: T[], size: number) {
  if (items.length === 0) return [[]] as T[][];
  const chunks: T[][] = [];
  for (let index = 0; index < items.length; index += size) chunks.push(items.slice(index, index + size));
  return chunks;
}
